# ─────────────────────────────────────────────────────────────────────────────
# FIGURE 8 – Throughput (Orders Completed per Unit Time)
# ─────────────────────────────────────────────────────────────────────────────
def fig_throughput(data: pd.DataFrame, output_dir: str):
    schedulers = ordered_schedulers(data)
    switch_times = sorted(data["SwitchTime"].unique())
    n_st = len(switch_times)

    fig, axes = plt.subplots(1, n_st, figsize=(5 * n_st, 5), sharey=True)
    fig.suptitle("Throughput: Completed Orders / Total Elapsed Time\n"
                 "Higher = better",
                 fontsize=12, fontweight="bold")
    if n_st == 1:
        axes = [axes]

    for ax, st in zip(axes, switch_times):
        throughputs = []
        colors = []
        for sched in schedulers:
            sub = data[(data["Scheduler"] == sched) & (data["SwitchTime"] == st)]
            if sub.empty or "CompletionTime" not in sub.columns or "ArrivalTime" not in sub.columns:
                throughputs.append(0)
            else:
                elapsed = sub["CompletionTime"].max() - sub["ArrivalTime"].min()
                throughputs.append(len(sub) / elapsed * 1000 if elapsed > 0 else 0)
            colors.append(sched_color(sched))
        bars = ax.bar(schedulers, throughputs, color=colors, edgecolor="white")
        for bar, v in zip(bars, throughputs):
            ax.text(bar.get_x() + bar.get_width() / 2,
                    bar.get_height() + 0.002, f"{v:.3f}",
                    ha="center", va="bottom", fontsize=8)
        ax.set_title(f"Switch Time = {st}ms", fontsize=10, fontweight="bold")
        ax.set_ylabel("Orders / ms" if st == switch_times[0] else "", fontsize=9)
        ax.set_xticklabels(schedulers, fontsize=9)

    plt.tight_layout()
    save(fig, output_dir, "08_throughput")


