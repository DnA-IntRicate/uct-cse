# FIGURE 4 – Effect of Context Switch Time on Each Metric
# =============================================================================
def fig_switch_time_effect(data: pd.DataFrame, output_dir: str):
    metric_cols = [m for m in METRICS if m in data.columns]
    schedulers = ordered_schedulers(data)
    switch_times = sorted(data["SwitchTime"].unique())
    n = len(metric_cols)

    fig, axes = plt.subplots(1, n, figsize=(5 * n, 5))
    fig.suptitle("Effect of Context Switch Time on Performance Metrics",
                 fontsize=13, fontweight="bold")

    for ax, metric in zip(axes, metric_cols):
        for sched in schedulers:
            means, stds = [], []
            for st in switch_times:
                sub = data[(data["Scheduler"] == sched) & (data["SwitchTime"] == st)][metric].dropna()
                means.append(sub.mean())
                stds.append(sub.std())
            means, stds = np.array(means), np.array(stds)
            ax.plot(switch_times, means, marker="o", label=sched,
                    color=sched_color(sched), linewidth=2, markersize=6)
            ax.fill_between(switch_times, means - stds, means + stds,
                            alpha=0.12, color=sched_color(sched))

        ax.set_xticks(switch_times)
        ax.set_xticklabels([f"ST={st}ms" for st in switch_times], fontsize=8)
        ax.set_ylabel("Mean Time (ms)", fontsize=9)
        ax.set_title(METRICS[metric].replace(" (ms)", ""), fontsize=10, fontweight="bold")
        ax.legend(fontsize=8)

    plt.tight_layout()
    save(fig, output_dir, "04_switch_time_effect")


