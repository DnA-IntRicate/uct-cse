# FIGURE 1 – Summary Statistics Table (mean, median, std, min, max)
# =============================================================================
def fig_summary_table(data: pd.DataFrame, output_dir: str):
    schedulers = ordered_schedulers(data)
    metric_cols = [m for m in METRICS if m in data.columns]
    records = []
    for sched in schedulers:
        sub = data[data["Scheduler"] == sched]
        for metric in metric_cols:
            col = sub[metric].dropna()
            records.append({
                "Scheduler": sched,
                "Metric":    METRICS[metric],
                "Mean":      col.mean(),
                "Median":    col.median(),
                "Std Dev":   col.std(),
                "Min":       col.min(),
                "Max":       col.max(),
            })
    table_df = pd.DataFrame(records)

    n_metrics = len(metric_cols)
    fig, axes = plt.subplots(1, n_metrics, figsize=(5 * n_metrics, 4))
    fig.suptitle("Summary Statistics by Scheduler & Metric\n(all switch times combined)",
                 fontsize=13, fontweight="bold", y=1.02)

    for ax, metric in zip(axes, metric_cols):
        sub = table_df[table_df["Metric"] == METRICS[metric]][
            ["Scheduler", "Mean", "Median", "Std Dev"]
        ].set_index("Scheduler")
        sub = sub.reindex(schedulers)
        sub_rounded = sub.round(1)

        ax.axis("off")
        tbl = ax.table(
            cellText=sub_rounded.values,
            rowLabels=sub_rounded.index,
            colLabels=sub_rounded.columns,
            cellLoc="center", rowLoc="center", loc="center",
        )
        tbl.auto_set_font_size(False)
        tbl.set_fontsize(9)
        tbl.scale(1.4, 1.8)

        # Color header
        for (r, c), cell in tbl.get_celld().items():
            if r == 0:
                cell.set_facecolor("#2c3e50")
                cell.set_text_props(color="white", fontweight="bold")
            elif c == -1:
                cell.set_facecolor(sched_color(str(sub_rounded.index[r - 1])))
                cell.set_text_props(color="white", fontweight="bold")
            else:
                cell.set_facecolor("#f9f9f9" if r % 2 == 0 else "white")

        ax.set_title(METRICS[metric], fontsize=10, fontweight="bold", pad=8)

    plt.tight_layout()
    save(fig, output_dir, "01_summary_table")


