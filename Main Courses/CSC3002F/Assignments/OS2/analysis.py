# FIGURE 3 – Box Plots: Distribution per Metric
# =============================================================================
def fig_boxplots(data: pd.DataFrame, output_dir: str):
    metric_cols = [m for m in METRICS if m in data.columns]
    schedulers = ordered_schedulers(data)
    n = len(metric_cols)
    fig, axes = plt.subplots(1, n, figsize=(4.5 * n, 5))
    fig.suptitle("Distribution of Metrics by Scheduler\n(Box plots — all switch times)",
                 fontsize=13, fontweight="bold")

    for ax, metric in zip(axes, metric_cols):
        plot_data = [data[data["Scheduler"] == s][metric].dropna().values
                     for s in schedulers]
        bp = ax.boxplot(plot_data, patch_artist=True, notch=False,
                        medianprops=dict(color="black", linewidth=2),
                        whiskerprops=dict(linewidth=1.2),
                        capprops=dict(linewidth=1.5),
                        flierprops=dict(marker="o", markersize=3, alpha=0.4,
                                        markeredgewidth=0))
        for patch, sched in zip(bp["boxes"], schedulers):
            patch.set_facecolor(sched_color(sched))
            patch.set_alpha(0.75)

        ax.set_xticks(range(1, len(schedulers) + 1))
        ax.set_xticklabels(schedulers, fontsize=8)
        ax.set_ylabel("Time (ms)", fontsize=9)
        ax.set_title(METRICS[metric].replace(" (ms)", ""), fontsize=10, fontweight="bold")

    plt.tight_layout()
    save(fig, output_dir, "03_boxplots")


