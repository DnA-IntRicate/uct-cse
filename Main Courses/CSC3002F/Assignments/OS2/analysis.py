# FIGURE 14 – MLFQ Queue Level Distribution (bonus insight)
# ─────────────────────────────────────────────────────────────────────────────
def fig_mlfq_queue_levels(data: pd.DataFrame, output_dir: str):
    mlfq = data[data["Scheduler"] == "MLFQ"]
    if mlfq.empty or "QueueLevel" not in mlfq.columns:
        return
    levels = sorted(mlfq["QueueLevel"].dropna().unique())
    if not levels:
        return

    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    fig.suptitle("MLFQ: Queue Level Distribution",
                 fontsize=12, fontweight="bold")

    # Count distribution
    counts = mlfq["QueueLevel"].value_counts().reindex(levels, fill_value=0)
    axes[0].bar([f"Q{int(l)}" for l in levels], counts.values,
                color="#8172B2", edgecolor="white")
    axes[0].set_title("Order Count per Queue Level", fontsize=10, fontweight="bold")
    axes[0].set_ylabel("Count")

    # Waiting time by queue level
    box_data = [mlfq[mlfq["QueueLevel"] == l]["WaitingTime"].dropna().values
                for l in levels]
    bp = axes[1].boxplot(box_data, patch_artist=True,
                         medianprops=dict(color="black", linewidth=2))
    for patch in bp["boxes"]:
        patch.set_facecolor("#8172B2")
        patch.set_alpha(0.65)
    axes[1].set_xticklabels([f"Q{int(l)}" for l in levels])
    axes[1].set_title("Waiting Time per Queue Level", fontsize=10, fontweight="bold")
    axes[1].set_ylabel("Waiting Time (ms)")

    plt.tight_layout()
    save(fig, output_dir, "14_mlfq_queue_levels")


