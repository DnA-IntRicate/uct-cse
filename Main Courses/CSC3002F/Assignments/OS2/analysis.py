# ─────────────────────────────────────────────────────────────────────────────
# FIGURE 13 – Statistical Significance (Kruskal-Wallis + pairwise Mann-Whitney)
# ─────────────────────────────────────────────────────────────────────────────
def fig_pvalue_heatmap(data: pd.DataFrame, output_dir: str):
    metric_cols = [m for m in METRICS if m in data.columns]
    schedulers  = ordered_schedulers(data)
    n = len(metric_cols)

    fig, axes = plt.subplots(1, n, figsize=(4 * n, 4))
    fig.suptitle("Pairwise Statistical Significance (Mann-Whitney U, p-values)\n"
                 "Blue = significantly different (p<0.05); Red = not significant",
                 fontsize=12, fontweight="bold")

    for ax, metric in zip(axes, metric_cols):
        p_matrix = pd.DataFrame(index=schedulers, columns=schedulers, dtype=float)
        for s1 in schedulers:
            for s2 in schedulers:
                if s1 == s2:
                    p_matrix.loc[s1, s2] = 1.0
                else:
                    v1 = data[data["Scheduler"] == s1][metric].dropna().values
                    v2 = data[data["Scheduler"] == s2][metric].dropna().values
                    if len(v1) > 0 and len(v2) > 0:
                        _, p = stats.mannwhitneyu(v1, v2, alternative="two-sided")
                        p_matrix.loc[s1, s2] = p
                    else:
                        p_matrix.loc[s1, s2] = np.nan

        p_matrix = p_matrix.astype(float)
        sns.heatmap(p_matrix, ax=ax, annot=True, fmt=".3f",
                    cmap="RdYlBu_r", vmin=0, vmax=0.2,
                    linewidths=0.5, linecolor="white",
                    cbar_kws={"shrink": 0.8})
        ax.set_title(METRICS[metric].replace(" (ms)", ""), fontsize=10, fontweight="bold")
        ax.set_xticklabels(ax.get_xticklabels(), rotation=45, ha="right", fontsize=8)
        ax.set_yticklabels(ax.get_yticklabels(), rotation=0, fontsize=8)

    plt.tight_layout()
    save(fig, output_dir, "13_pvalue_heatmap")


